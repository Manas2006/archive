// Web app build (an installable PWA for iPhone, iPad and Android), from the same
// page modules as the extension: `vite build -c vite.web.config.ts` writes dist-web/.
// WEB_BASE sets the path it's served from (default /archive/, for GitHub Pages).

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from 'tailwindcss';
import autoprefixer from 'autoprefixer';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const WEB = path.join(ROOT, 'web');
const OUT = path.join(ROOT, 'dist-web');
const PDFJS = path.join(ROOT, 'node_modules/pdfjs-dist');
const BASE = `/${(process.env.WEB_BASE ?? '/archive/').replace(/^\/+|\/+$/g, '')}/`.replace(/^\/\/$/, '/');
const VERSION: string = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
const PAGES = ['index', 'library', 'reader', 'options'];

// the extension's Tailwind setup, with content paths that work from any working directory
const tailwindConfig = {
  ...createRequire(import.meta.url)(path.join(ROOT, 'tailwind.config.cjs')),
  content: [path.join(ROOT, 'src/**/*.{ts,tsx,html}'), path.join(WEB, '**/*.{ts,html}')],
};

/** pdf.js character maps and standard fonts, at the /pdfjs/ path the reader asks for (see reader/pdf.ts). */
function pdfjsAssets(): Plugin {
  const dirs = ['cmaps', 'standard_fonts'];
  return {
    name: 'archive-pdfjs-assets',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const m = req.url?.split('?')[0].match(/\/pdfjs\/(cmaps|standard_fonts)\/([^/]+)$/);
        const file = m && path.join(PDFJS, m[1], path.basename(m[2]));
        if (!file || !fs.existsSync(file)) return next();
        res.setHeader('content-type', 'application/octet-stream');
        fs.createReadStream(file).pipe(res);
      });
    },
    generateBundle() {
      for (const dir of dirs) {
        for (const f of fs.readdirSync(path.join(PDFJS, dir))) {
          this.emitFile({ type: 'asset', fileName: `pdfjs/${dir}/${f}`, source: fs.readFileSync(path.join(PDFJS, dir, f)) });
        }
      }
    },
  };
}

function walk(dir: string, rel = ''): string[] {
  return fs.readdirSync(path.join(dir, rel), { withFileTypes: true }).flatMap((e) => {
    const p = rel ? `${rel}/${e.name}` : e.name;
    return e.isDirectory() ? walk(dir, p) : [p];
  });
}

/**
 * A small service worker: the app shell (every built page, script, style and icon) is
 * cached under a versioned name so the app opens offline. Pages are network-first,
 * hashed assets cache-first, and arXiv PDFs are kept for offline reading.
 */
function serviceWorker(): Plugin {
  return {
    name: 'archive-service-worker',
    apply: 'build',
    enforce: 'post',
    writeBundle() {
      const files = walk(OUT).filter((f) => f !== 'sw.js' && !f.startsWith('pdfjs/') && !f.endsWith('.map'));
      const hash = createHash('sha256');
      for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(OUT, f)));
      const version = hash.digest('hex').slice(0, 12);
      const shell = ['./', ...files.map((f) => `./${f}`)];
      const sw = `// Generated by vite.web.config.ts. Archive web app: offline app shell and saved PDFs.
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = 'archive-shell-' + VERSION;
const RUNTIME_CACHE = 'archive-runtime';
const PDF_CACHE = 'archive-pdfs';
const MAX_PDFS = 40;
const SHELL = ${JSON.stringify(shell)};
const SCOPE = new URL('./', self.location).pathname;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(SHELL_CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('archive-shell-') && k !== SHELL_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

async function networkFirst(request, cacheName, fallbackUrl, key = request) {
  try {
    const res = await fetch(request);
    if (res.ok) {
      const cache = await caches.open(cacheName);
      await cache.put(key, res.clone());
    }
    return res;
  } catch (e) {
    const hit = (await caches.match(request, { ignoreSearch: true })) || (fallbackUrl && (await caches.match(fallbackUrl)));
    if (hit) return hit;
    throw e;
  }
}

async function cacheFirst(request) {
  const hit = await caches.match(request);
  if (hit) return hit;
  const res = await fetch(request);
  if (res.ok) {
    const cache = await caches.open(RUNTIME_CACHE);
    await cache.put(request, res.clone());
  }
  return res;
}

async function trimPdfs() {
  const cache = await caches.open(PDF_CACHE);
  const keys = await cache.keys();
  for (const k of keys.slice(0, Math.max(0, keys.length - MAX_PDFS))) await cache.delete(k);
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin === self.location.origin && url.pathname.startsWith(SCOPE)) {
    if (req.mode === 'navigate' || url.pathname.endsWith('.html') || url.pathname === SCOPE) {
      // one cached copy per page, whatever its query (reader.html?src=...)
      event.respondWith(networkFirst(req, SHELL_CACHE, SCOPE, url.origin + url.pathname));
    } else {
      event.respondWith(cacheFirst(req));
    }
    return;
  }
  // arXiv PDFs: fresh when online, the saved copy when not
  if (url.hostname === 'arxiv.org' && url.pathname.startsWith('/pdf/')) {
    event.respondWith(
      networkFirst(req, PDF_CACHE).then((res) => {
        event.waitUntil(trimPdfs());
        return res;
      }),
    );
  }
});
`;
      fs.writeFileSync(path.join(OUT, 'sw.js'), sw);
      // GitHub Pages: serve files and folders as-is (no Jekyll processing)
      fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
    },
  };
}

export default defineConfig({
  root: WEB,
  base: BASE,
  publicDir: path.join(WEB, 'public'),
  resolve: {
    alias: { '@': path.join(ROOT, 'src'), '~': path.join(ROOT, 'src') },
  },
  define: {
    __ARCHIVE_WEB__: 'true',
    __ARCHIVE_VERSION__: JSON.stringify(VERSION),
  },
  css: {
    postcss: { plugins: [tailwindcss(tailwindConfig), autoprefixer()] },
  },
  plugins: [react(), pdfjsAssets(), serviceWorker()],
  build: {
    outDir: OUT,
    emptyOutDir: true,
    // pdf.js 4 needs Safari 17.4 / Chrome 119 features anyway
    target: ['es2022', 'safari16.4', 'chrome111', 'firefox115'],
    chunkSizeWarningLimit: 2000,
    rollupOptions: {
      input: Object.fromEntries(PAGES.map((p) => [p, path.join(WEB, `${p}.html`)])),
    },
  },
});
